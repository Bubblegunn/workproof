import { test, after } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { execFileSync } from "node:child_process";
import { computeFigures, renderFigures } from "../src/figures.js";
import type { FiguresResult } from "../src/figures.js";

const dirs: string[] = [];
after(async () => {
  for (const d of dirs) await rm(d, { recursive: true, force: true });
});

interface Who { name: string; email: string }
const ADA: Who = { name: "Ada", email: "ada@example.com" };
const BOB: Who = { name: "Bob", email: "bob@example.com" };

function git(dir: string, args: string[], who: Who = ADA, date = "2026-01-05T10:00:00Z"): string {
  const env = {
    ...process.env,
    GIT_AUTHOR_NAME: who.name,
    GIT_AUTHOR_EMAIL: who.email,
    GIT_COMMITTER_NAME: who.name,
    GIT_COMMITTER_EMAIL: who.email,
    GIT_AUTHOR_DATE: date,
    GIT_COMMITTER_DATE: date,
    GIT_CONFIG_GLOBAL: "/dev/null",
    GIT_CONFIG_SYSTEM: "/dev/null",
  } as Record<string, string>;
  return execFileSync("git", args, { cwd: dir, encoding: "utf8", env });
}

async function write(dir: string, rel: string, text: string): Promise<void> {
  await mkdir(join(dir, dirname(rel)), { recursive: true });
  await writeFile(join(dir, rel), text);
}

/** `n` numbered lines, each built by `fmt`, with a final newline. */
const numbered = (fmt: (i: number) => string, n: number): string => Array.from({ length: n }, (_, i) => fmt(i)).join("\n") + "\n";
const utilText = numbered((i) => `export const u${i} = ${i};`, 30);

/**
 * Ada (the identity) makes ten non-merge commits, Bob one, all in January 2026. The raw added lines of Ada are 233:
 *   vendor/lib/parse.js 12 (vendored path), vendor/lib/mit-lib.js 6 (MIT header, also vendored: the header is counted first),
 *   src/mit.ts 10 (MIT header), src/gen.ts 8 (@generated marker), src/util.ts 30 (kept),
 *   src/util-copy.ts 30 (byte-identical to util.ts), src/normal.ts 6 (kept; reindented later, the reindent adds 6 whitespace lines),
 *   src/temp.ts 5 (added, then reverted: kept), src/big.ts 120 (kept; 51.5% of Ada's lines).
 * Excluded: header 16, vendored or generated 20, whitespace-only 6, exact copies 30 = 72. Net 161.
 */
async function buildRepo(): Promise<{ dir: string; sha: Record<string, string> }> {
  const dir = await mkdtemp(join(tmpdir(), "workproof-lines-"));
  dirs.push(dir);
  git(dir, ["init", "-q", "-b", "main"]);
  const sha: Record<string, string> = {};
  const commit = async (key: string, who: Who, date: string, message: string) => {
    git(dir, ["add", "-A"], who, date);
    git(dir, ["commit", "-q", "--allow-empty", "-m", message], who, date);
    sha[key] = git(dir, ["rev-parse", "HEAD"]).trim();
  };

  await write(dir, "src/util.ts", utilText);
  await commit("util", ADA, "2026-01-05T10:00:00Z", "add util");

  await write(dir, "vendor/lib/parse.js", numbered((i) => `const v${i} = ${i};`, 12));
  await write(dir, "vendor/lib/mit-lib.js", "// MIT License\n" + numbered((i) => `const w${i} = ${i};`, 5));
  await commit("vendor", ADA, "2026-01-06T10:00:00Z", "vendor the parser");

  await write(dir, "src/mit.ts", "// Licensed under the MIT License\n" + numbered((i) => `export const m${i} = ${i};`, 9));
  await commit("mit", ADA, "2026-01-07T10:00:00Z", "add mit file");

  await write(dir, "src/gen.ts", "// @generated by codegen. Do not edit.\n" + numbered((i) => `export const g${i} = ${i};`, 7));
  await commit("gen", ADA, "2026-01-08T10:00:00Z", "add generated output");

  await write(dir, "src/normal.ts", numbered((i) => `export const n${i} = ${i};`, 6));
  await commit("normal", ADA, "2026-01-09T10:00:00Z", "add normal file");

  await write(dir, "src/util-copy.ts", utilText);
  await commit("copy", ADA, "2026-01-10T10:00:00Z", "copy util under a new name");

  await write(dir, "src/normal.ts", numbered((i) => `  export const n${i} = ${i};`, 6));
  await commit("reindent", ADA, "2026-01-12T10:00:00Z", "reindent normal");

  await write(dir, "src/temp.ts", numbered((i) => `export const t${i} = ${i};`, 5));
  await commit("temp", ADA, "2026-01-13T10:00:00Z", "add temp");

  git(dir, ["revert", "--no-edit", sha.temp!], ADA, "2026-01-14T10:00:00Z");
  sha.revert = git(dir, ["rev-parse", "HEAD"]).trim();

  await write(dir, "src/big.ts", numbered((i) => `export const b${i} = ${i};`, 120));
  await commit("big", ADA, "2026-01-15T10:00:00Z", "add big file");

  await write(dir, "src/bob.ts", numbered((i) => `export const q${i} = ${i};`, 5));
  await commit("bob", BOB, "2026-01-16T10:00:00Z", "bob adds five lines");

  return { dir, sha };
}

const row = (r: FiguresResult, label: string) => {
  const found = r.rows.find((x) => x.label === label);
  assert.ok(found, `no row labelled ${label}`);
  return found;
};

test("the net figure is exactly the raw lines minus each exclusion, once", async () => {
  const { dir } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  assert.equal(row(r, "lines added, raw").value, 233);
  const net = row(r, "lines written, net of exclusions");
  assert.equal(net.computed, true);
  assert.equal(net.value, 161);
  assert.match(net.filter, /\(a\) third-party header/);
  assert.match(net.filter, /\(d\) exact copies/);
  assert.match(net.filter, /reverted work is not subtracted/);
  assert.match(net.filter, /9 of 9 added files inspected/);
});

test("the reason breakdown: header 16, vendored or generated 20, whitespace-only 6, exact copies 30", async () => {
  const { dir } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const excluded = row(r, "lines excluded, by reason");
  assert.equal(excluded.computed, true);
  assert.equal(excluded.value, "third-party header 16, vendored or generated path 20, whitespace-only commits 6, exact copies 30");
  assert.equal(row(r, "whitespace-only commits").value, 1);
});

test("a header in a vendored file is counted under the header reason, which comes first", async () => {
  const { dir } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const excluded = row(r, "lines excluded, by reason");
  // mit-lib.js is both vendored and headed: 6 lines under the header (16 = 10 + 6), not under vendored (20 = 12 + 8).
  assert.match(excluded.value as string, /third-party header 16,/);
  assert.match(excluded.value as string, /vendored or generated path 20,/);
});

test("the detail names the largest excluded files, with reason and the copy source", async () => {
  const { dir, sha } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const detail = row(r, "lines excluded, by reason").detail ?? [];
  assert.equal(detail.length, 5);
  assert.ok(detail.includes(`${sha.copy!.slice(0, 7)} "src/util-copy.ts" 30 lines, exact copies: copy of "src/util.ts" from ${sha.util!.slice(0, 7)}`), detail.join("\n"));
  assert.ok(detail.some((d) => d.includes('"vendor/lib/parse.js" 12 lines, vendored or generated path: path rule')), detail.join("\n"));
  assert.ok(detail.some((d) => d.includes('"src/mit.ts" 10 lines, third-party header: licence')), detail.join("\n"));
});

test("a generated file with an @generated marker is excluded as generated", async () => {
  const { dir, sha } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const detail = row(r, "lines excluded, by reason").detail ?? [];
  assert.ok(detail.some((d) => d.includes(`${sha.gen!.slice(0, 7)} "src/gen.ts" 8 lines, vendored or generated path: generated marker`)), detail.join("\n"));
});

test("the largest commit holding over half the lines is reported with its percentage and subject", async () => {
  const { dir, sha } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const largest = row(r, "largest commit by lines added");
  assert.equal(largest.value, `${sha.big!.slice(0, 7)}, 120 lines, 51.5% of the identity's lines added`);
  assert.deepEqual(largest.detail, ['subject "add big file"']);
});

test("a revert pair stays in the number: the reverted file is still counted, the revert adds nothing", async () => {
  const { dir } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  assert.equal(row(r, "revert commits").value, 1);
  // 161 includes the 5 lines of src/temp.ts; had the revert been subtracted it would be 156.
  assert.equal(row(r, "lines written, net of exclusions").value, 161);
});

test("share rows: the identity's share of non-merge commits and of lines added, one decimal, denominators in the filter", async () => {
  const { dir } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const commits = row(r, "share of non-merge commits by the identity");
  assert.equal(commits.value, "90.9%");
  assert.match(commits.filter, /denominator 11, bots included/);
  const lines = row(r, "share of lines added by the identity");
  assert.equal(lines.value, "97.9%");
  assert.match(lines.filter, /denominator 238, bots included/);
});

test("the new rows sit right after 'lines deleted, whitespace ignored'", async () => {
  const { dir } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const labels = r.rows.map((x) => x.label);
  const at = labels.indexOf("lines deleted, whitespace ignored");
  assert.deepEqual(labels.slice(at + 1, at + 7), [
    "lines written, net of exclusions",
    "lines excluded, by reason",
    "lines written, reverts removed",
    "largest commit by lines added",
    "share of non-merge commits by the identity",
    "share of lines added by the identity",
  ]);
});

test("the text output stays within the 60-line cap and still shows the net figure", async () => {
  const { dir } = await buildRepo();
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  const text = renderFigures(r);
  assert.ok(text.trimEnd().split("\n").length <= 60, `${text.trimEnd().split("\n").length} lines`);
  assert.match(text, /lines written, net of exclusions \| 161 \|/);
});

test("a repository with no commits: every new figure is not computed, never 0", async () => {
  const dir = await mkdtemp(join(tmpdir(), "workproof-lines-empty-"));
  dirs.push(dir);
  git(dir, ["init", "-q", "-b", "main"]);
  const r = await computeFigures({ repo: dir, authors: [ADA.email], json: false });
  for (const label of ["lines written, net of exclusions", "lines excluded, by reason", "largest commit by lines added", "share of non-merge commits by the identity", "share of lines added by the identity"]) {
    const found = row(r, label);
    assert.equal(found.computed, false, label);
    assert.match(String(found.value), /^not computed \(/, label);
  }
  assert.match(renderFigures(r), /lines written, net of exclusions \| not computed \(/);
});
