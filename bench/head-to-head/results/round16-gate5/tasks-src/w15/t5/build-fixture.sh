#!/usr/bin/env bash
REPO_URL=https://github.com/dbader/schedule; PIN=82a43db1b938d8fdf60103bd41f329e06c8d3651
set -euo pipefail
[ $# -eq 1 ] || { echo "usage: $0 <dest-dir>" >&2; exit 2; }
DEST="$1"; case "$DEST" in /*) ;; *) DEST="$PWD/$DEST";; esac
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null GIT_TERMINAL_PROMPT=0
export TZ=UTC LC_ALL=C
rm -rf "$DEST"; mkdir -p "$(dirname "$DEST")"
git clone -q "$REPO_URL" "$DEST"
G() { git -C "$DEST" "$@"; }
G checkout -q -B fixture "$PIN"
for b in $(G for-each-ref --format='%(refname:short)' refs/heads); do [ "$b" = fixture ] || G branch -q -D "$b"; done
for r in $(G remote); do G remote remove "$r"; done
for t in $(G tag -l); do G tag -d "$t" >/dev/null; done
# c <author-name> <author-email> <author-date> <message> [committer-name committer-email committer-date]
c() {
  G add -A
  GIT_AUTHOR_NAME="$1" GIT_AUTHOR_EMAIL="$2" GIT_AUTHOR_DATE="$3" \
  GIT_COMMITTER_NAME="${5:-$1}" GIT_COMMITTER_EMAIL="${6:-$2}" GIT_COMMITTER_DATE="${7:-$3}" \
  G -c commit.gpgsign=false -c core.hooksPath=/dev/null commit -q --allow-empty -m "$4"
}
finish() {
  G branch -q -m fixture main
  G reflog expire --expire=now --all
  G gc -q --prune=now
  echo "HEAD $(G rev-parse HEAD)"
}
w() { mkdir -p "$(dirname "$DEST/$1")"; cat > "$DEST/$1"; }

# ---- lab history -------------------------------------------------------
# rules <file> <n> <tag>: n small functions (2 lines each) plus a header
rules() { mkdir -p "$(dirname "$DEST/$1")"; awk -v n="$2" -v t="$3" 'BEGIN{print "# " t; for(i=1;i<=n;i++){print "def rule_" i "(x):"; print "    return x*" i "+1"}}' > "$DEST/$1"; }

w .gitattributes <<'EOF'
vendor/** linguist-vendored
docs/_generated/** linguist-generated
EOF
c "Frank Ito" frank.ito@lab.example "2025-06-01T09:00:00+0000" "chore: mark vendored and generated paths"

rules lab/legacy.py 50 "legacy cleaning rules"
c "Mia Rossi" mia.rossi@lab.example "2025-06-10T10:00:00+0000" "add legacy cleaning rules (before the reporting window)"

mkdir -p "$DEST/vendor/fastcsv"
for f in reader writer dialect; do awk -v f="$f" 'BEGIN{for(i=1;i<=1000;i++) print "FASTCSV_" f "_" i " = " i*7}' > "$DEST/vendor/fastcsv/$f.py"; done
c "Noah Berg" noah.berg@lab.example "2025-11-10T10:00:00+0000" "vendor fastcsv 2.3"

mkdir -p "$DEST/data"
awk 'BEGIN{for(i=1;i<=50000;i++) print i ",station" (i%9) "," i*0.37}' > "$DEST/data/measurements.csv"
python3 -c "
import sys
open(sys.argv[1], 'wb').write(bytes((i * 37) % 256 for i in range(4096)))
" "$DEST/data/figure1.png"
printf '# Data\n\nField measurements, station 0-8.\n' > "$DEST/data/README.md"
c "Mia Rossi" mia.rossi@lab.example "2025-11-20T11:00:00+0000" "add field measurements and figure"

rules lab/clean.py 60 "cleaning rules"
c "Mia Rossi" m.rossi@gmail.example "2025-12-02T20:00:00+0000" "cleaning rules for the 2025 campaign"

awk 'BEGIN{print "# Model"; for(i=1;i<=100;i++){print "def stage_" i "(x):"; print "    return x*" i "+" i}}' > "$DEST/lab/model.py"
c "Oscar Lind" oscar.lind@lab.example "2025-12-15T14:00:00+0000" "model stages"

mkdir -p "$DEST/tests"
awk 'BEGIN{print "from lab import model"; for(i=1;i<=40;i++){print "def test_stage_" i "():"; print "    assert model.stage_" i "(0) == " i}}' > "$DEST/tests/test_model.py"
c "Oscar Lind" oscar.lind@lab.example "2025-12-16T09:00:00+0000" "tests for model stages"

mkdir -p "$DEST/lab/gen"
{ echo "# Generated by the protocol buffer compiler.  DO NOT EDIT!"; awk 'BEGIN{for(i=1;i<=800;i++) print "_FIELD_" i " = " i}'; } > "$DEST/lab/gen/schema_pb2.py"
c "Noah Berg" noah.berg@lab.example "2026-01-08T10:00:00+0000" "regenerate protobuf bindings"

mkdir -p "$DEST/docs/_generated"
awk 'BEGIN{for(i=1;i<=4000;i++) print "<li id=\"api" i "\">entry " i "</li>"}' > "$DEST/docs/_generated/api.html"
c "Oscar Lind" oscar.lind@lab.example "2026-01-20T10:00:00+0000" "rebuild API docs"

# a shared lab PC with one git identity; initials only in the messages
awk 'BEGIN{print "# plots"; for(i=1;i<=50;i++) print "AXIS_" i " = \"label " i "\""}' > "$DEST/lab/plots.py"
c "lab-pc-3" labpc3@lab.example "2026-02-03T15:00:00+0000" "plots: axis labels (PV)"
for k in 1 2 3; do
  awk -v k="$k" 'BEGIN{for(i=1;i<=40;i++) print "COLOR_" k "_" i " = \"#" i "0" k "\""}' >> "$DEST/lab/plots.py"
  c "lab-pc-3" labpc3@lab.example "2026-02-0$((3+k))T15:00:00+0000" "plots: colour set $k (QY)"
done

perl -pi -e 's/return x\*(\d+)\+(\d+)/return x * $1 + $2/' "$DEST/lab/model.py"
c "Oscar Lind" oscar.lind@lab.example "2026-03-10T12:00:00+0000" "style: apply black to lab/model.py"

mkdir -p "$DEST/lab/models"
G mv lab/model.py lab/models/model.py
sed -i.bak 's/from lab import model/from lab.models import model/' "$DEST/tests/test_model.py"; rm -f "$DEST/tests/test_model.py.bak"
c "Noah Berg" noah.berg@lab.example "2026-04-02T10:00:00+0000" "move model into lab/models/"

awk 'BEGIN{for(i=1;i<=600;i++) print "pinned-package-" i "==1." i ".0 --hash=sha256:" i}' > "$DEST/requirements.lock"
c "Frank Ito" frank.ito@lab.example "2026-05-04T10:00:00+0000" "update lock file"

echo "pinned-package-601==1.0 --hash=sha256:0" >> "$DEST/requirements.lock"
c "dependabot[bot]" "49699333+dependabot[bot]@users.noreply.example" "2026-06-01T04:00:00+0000" "Bump pinned-package"

rules lab/report.py 25 "report helpers"
c "Mia Rossi" mia.rossi@lab.example "2026-07-14T10:00:00+0000" "report helpers"

printf '\n## Lab usage\n\nSee lab/ for the analysis code and data/ for the datasets.\n' >> "$DEST/README.rst"
c "Frank Ito" frank.ito@lab.example "2026-08-03T10:00:00+0000" "docs: lab usage section"

finish
