# ci <author> <email> <author-date> <message> [committer-date] [committer] [committer-email]
ci() {
  local an="$1" ae="$2" ad="$3" msg="$4" cd="${5:-$3}" cn="${6:-$1}" ce="${7:-$2}"
  git add -A
  GIT_AUTHOR_NAME="$an" GIT_AUTHOR_EMAIL="$ae" GIT_AUTHOR_DATE="$ad" \
  GIT_COMMITTER_NAME="$cn" GIT_COMMITTER_EMAIL="$ce" GIT_COMMITTER_DATE="$cd" \
  git commit -q --allow-empty -m "$msg"
}
# gen <n-lines> <tag> [indent-width] : n rust-ish lines, 3 per function
gen() { awk -v n="$1" -v t="$2" -v w="${3:-2}" 'BEGIN{pad=sprintf("%*s",w,""); for(i=0;i<n;i++){k=1+int(i/3); r=i%3; if(r==0) printf "fn %s_%d() -> i32 {\n", t, k; else if(r==1) printf "%s%d\n", pad, k; else printf "}\n"}}'; }
put() { mkdir -p "$(dirname "$1")"; gen "$2" "$3" "${4:-2}" >> "$1"; }   # put <file> <n> <tag> [indent]

