/// Number of decimal digits needed to print `n` (no sign).
#[inline]
pub fn digits10(mut n: u64) -> usize {
    let mut digits = 1;
    while n >= 10_000 {
        digits += 4;
        n /= 10_000;
    }
    if n >= 1_000 {
        digits += 3;
    } else if n >= 100 {
        digits += 2;
    } else if n >= 10 {
        digits += 1;
    }
    digits
}
