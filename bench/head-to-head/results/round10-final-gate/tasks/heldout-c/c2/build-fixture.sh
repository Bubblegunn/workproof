#!/usr/bin/env bash
# build-fixture.sh <dest-dir> : logrus (Go) + synthetic history for task c2
set -euo pipefail
DEST=${1:?usage: build-fixture.sh <dest-dir>}
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null
rm -rf "$DEST"
git clone -q https://github.com/sirupsen/logrus "$DEST"
cd "$DEST"
git checkout -q -B main d1e6332644483cfee14de11099f03645561d55f8
git remote remove origin
git tag -l | xargs -r git tag -d >/dev/null
git for-each-ref refs/heads --format='%(refname:short)' | grep -v '^main$' | xargs -r git branch -D >/dev/null || true

# c NAME EMAIL DATE MSG [COMMITTER_DATE]
c() {
  git add -A
  GIT_AUTHOR_NAME="$1" GIT_AUTHOR_EMAIL="$2" GIT_AUTHOR_DATE="$3" \
  GIT_COMMITTER_NAME="$1" GIT_COMMITTER_EMAIL="$2" GIT_COMMITTER_DATE="${5:-$3}" \
  git commit -q -m "$4"
}
